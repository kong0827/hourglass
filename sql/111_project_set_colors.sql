-- =====================================================================
-- 111_project_set_colors.sql · 项目集身份色默认分配（纯数据，无结构变更）
-- 用法（已有库升级，先全库备份）：
--   mysql -uroot -p --default-character-set=utf8mb4 hourglass < sql/111_project_set_colors.sql
-- 全新安装无需执行本文件（新库的项目集颜色由界面选择）。
--
-- 背景：项目列表改用「色标白底」方案，集身份色只用于 3px 左条、色标图标与树线；
--       现有项目集的 color 全部是默认 #8a8578，8 个集在列表上没有区分度。
-- 口径（2026-11-19 已确认）：
--   1. 只改仍是默认色 / 空值的集，用户自己选过的颜色不动。
--   2. 按集名分配 8 个身份色（与原型一致），不按 ID 或顺序推断。
--   3. 不在名单里的自定义集保持默认色，由用户在「编辑项目集」里选色。
--   4. 可重复执行：第二次执行时颜色已不是默认值，不会再被覆盖。
-- =====================================================================

UPDATE project_set
SET color = CASE name
      WHEN '流程引擎'     THEN '#4F5BD5'
      WHEN '资金通'       THEN '#0F766E'
      WHEN '风控管理'     THEN '#7A5AF8'
      WHEN 'API开放平台'  THEN '#0B7FA8'
      WHEN '技术平台'     THEN '#B45309'
      WHEN '项目管理平台' THEN '#C02676'
      WHEN '报表'         THEN '#6B7F0F'
      WHEN '其他项目'     THEN '#64748B'
      ELSE color
    END
WHERE name IN ('流程引擎','资金通','风控管理','API开放平台','技术平台','项目管理平台','报表','其他项目')
  AND (color IS NULL OR color = '' OR LOWER(color) = '#8a8578');
